"""The DEALS table, generated from the field list so that it cannot drift from the prompt and the schema.

    python -m motherlode.ddl          # prints the statement
    python -m motherlode.ddl --write  # rewrites sql/02_deals_table.sql

A test fails when the committed file differs from what this module generates.
"""
from __future__ import annotations

import sys
from pathlib import Path

from .fields import all_fields

TARGET = Path(__file__).resolve().parent.parent / "sql" / "02_deals_table.sql"

# Columns the pipeline adds around the extracted fields.
BEFORE = [("DOC_ID", "VARCHAR NOT NULL", "The announcement this row was extracted from (DOCUMENTS.DOC_ID).")]
AFTER = [
    ("CONTINENT", "VARCHAR", "Continent of the project, from AI_CLASSIFY."),
    ("DEAL_CATEGORY", "VARCHAR", "Deal type from a fixed list, from AI_CLASSIFY (deal_type is the model's free text)."),
    ("EXTRACTOR", "VARCHAR", "Which function produced the row: AI_COMPLETE with a model name, or AI_EXTRACT."),
    ("ATTEMPTS", "NUMBER(2)", "Extraction attempts used (2 means the corrected retry ran)."),
    ("OUTCOME", "VARCHAR", "stored, or stored_partial when unsupported values were withheld."),
    ("LOADED_AT", "TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()", "When the row was written."),
]


def _comment(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def deals_table() -> str:
    columns = BEFORE + [(f.name.upper(), f.sql_type, f.description) for f in all_fields()] + AFTER
    width = max(len(name) for name, _, _ in columns)
    lines = [f"    {name.ljust(width)}  {sql_type} COMMENT {_comment(comment)}" for name, sql_type, comment in columns]
    return (
        "-- Generated by `python -m motherlode.ddl --write` from the field list in motherlode/prompts.py. Do not edit.\n"
        "CREATE TABLE IF NOT EXISTS MOTHERLODE.CORE.DEALS (\n"
        + ",\n".join(lines)
        + ",\n    CONSTRAINT DEALS_PK PRIMARY KEY (DOC_ID)\n)\n"
        "COMMENT = 'One row per project transaction, written only after every number was checked against the announcement.';\n"
    )


def insert_deal_sql() -> str:
    """INSERT of one deal from a JSON object, with each value cast to its column type.

    Bind parameters, in order: doc id, continent, deal category, extractor, attempts, outcome, the row as JSON."""
    fields = all_fields()
    columns = ", ".join(f.name.upper() for f in fields)
    values = ", ".join(f"v:{f.name}::{f.sql_type}" for f in fields)
    return (f"INSERT INTO MOTHERLODE.CORE.DEALS (DOC_ID, {columns}, CONTINENT, DEAL_CATEGORY, EXTRACTOR, ATTEMPTS, OUTCOME)\n"
            f"SELECT ?, {values}, ?, ?, ?, ?, ? FROM (SELECT PARSE_JSON(?) AS v)")


if __name__ == "__main__":
    if "--write" in sys.argv:
        TARGET.write_text(deals_table())
        print(f"wrote {TARGET}")
    else:
        print(deals_table())
